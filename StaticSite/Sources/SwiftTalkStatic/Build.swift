import Foundation
import CommonMark

public struct BuildConfiguration {
    public var data: URL
    public var transcripts: URL
    public var assets: URL
    public var siteAssets: URL
    public var output: URL
    public var baseURL: URL
    public var asOf: Date
    public var pagefind: URL?

    public init(data: URL, transcripts: URL, assets: URL, siteAssets: URL, output: URL, baseURL: URL, asOf: Date = Date(), pagefind: URL? = nil) {
        self.data = data
        self.transcripts = transcripts
        self.assets = assets
        self.siteAssets = siteAssets
        self.output = output
        self.baseURL = baseURL
        self.asOf = asOf
        self.pagefind = pagefind
    }
}

public struct BuildSummary {
    public var episodes: Int
    public var collections: Int
    public var output: URL
}

/// Builds from explicit local content checkouts. No database, API tokens, or network calls.
@discardableResult public func buildSite(_ config: BuildConfiguration) throws -> BuildSummary {
    let fm = FileManager.default
    guard let scheme = config.baseURL.scheme, ["https", "http"].contains(scheme),
          config.baseURL.host != nil, config.baseURL.user == nil, config.baseURL.password == nil,
          config.baseURL.query == nil, config.baseURL.fragment == nil,
          ["", "/"].contains(config.baseURL.path) else {
        throw BuildError("--base-url must be a site origin, e.g. https://talk.objc.io (subdirectory hosting is not supported).")
    }
    let output = config.output.standardizedFileURL.resolvingSymlinksInPath()
    let inputs = [config.data, config.transcripts, config.assets, config.siteAssets].map { $0.standardizedFileURL.resolvingSymlinksInPath() }
    func contains(_ parent: URL, _ child: URL) -> Bool {
        parent.path == child.path || child.path.hasPrefix(parent.path + "/")
    }
    guard output.path != "/", !inputs.contains(where: { contains(output, $0) || contains($0, output) }) else {
        throw BuildError("The output directory must be separate from every input directory.")
    }
    let marker = ".swift-talk-static-output"
    if fm.fileExists(atPath: output.path) {
        guard fm.fileExists(atPath: output.appendingPathComponent(marker).path) else {
            throw BuildError("Refusing to replace \(output.path): it is not a generated Swift Talk site. Choose a new output directory.")
        }
    }
    let content = try Content(data: config.data, transcripts: config.transcripts, asOf: config.asOf)
    if let executable = config.pagefind, !fm.isExecutableFile(atPath: executable.path) {
        throw BuildError("Pagefind is missing at \(executable.path). Run npm ci --prefix StaticSite, or supply --pagefind PATH.")
    }
    let renderer = Renderer(content: content, baseURL: config.baseURL, assets: config.assets)
    let parent = output.deletingLastPathComponent()
    try fm.createDirectory(at: parent, withIntermediateDirectories: true)
    let staging = parent.appendingPathComponent(".swift-talk-build-\(UUID().uuidString)")
    try fm.createDirectory(at: staging, withIntermediateDirectories: true)
    defer { try? fm.removeItem(at: staging) }

    func write(_ text: String, _ path: String) throws {
        let file = staging.appendingPathComponent(path)
        try fm.createDirectory(at: file.deletingLastPathComponent(), withIntermediateDirectories: true)
        try text.write(to: file, atomically: true, encoding: .utf8)
    }
    func copy(_ source: URL, _ path: String) throws {
        let destination = staging.appendingPathComponent(path)
        try fm.createDirectory(at: destination.deletingLastPathComponent(), withIntermediateDirectories: true)
        try fm.copyItem(at: source, to: destination)
    }
    try write("Generated by swift-talk-static. Rebuild to replace.\n", marker)
    try write(renderer.home, "index.html")
    try write(renderer.episodesPage, "episodes/index.html")
    try write(renderer.collectionsPage, "collections/index.html")
    for collection in content.collections {
        try write(renderer.collectionPage(collection), "collections/\(collection.id)/index.html")
    }
    let highlighter = SwiftHighlighter()
    for episode in content.episodes {
        let raw = content.transcripts[episode.number]!
        let transcript = try Transcript(raw, highlighter: highlighter)
        try write(renderer.episodePage(episode, transcript: transcript), "episodes/\(episode.slug)/index.html")
        try write(raw, "transcripts/episode\(episode.number).md")
        try write(renderer.redirect(to: episode.path), "episodes/S01E\(episode.number)/index.html")
        let padded = String(format: "S01E%02d", episode.number)
        if padded != "S01E\(episode.number)" {
            try write(renderer.redirect(to: episode.path), "episodes/\(padded)/index.html")
            try write(renderer.redirect(to: episode.path), "episodes/\(padded)-\(episode.title.slug)/index.html")
        }
    }
    // The old server matched by number, so historical transcript links can have older titles.
    // Materialize those known aliases as static pages to preserve incoming links, too.
    var legacyLinks: [String] = []
    let sourceMarkdown = Array(content.transcripts.values) + content.episodes.map(\.synopsis)
        + content.episodes.flatMap { ($0.updates ?? []).map(\.text) } + content.collections.map(\.description)
    for source in sourceMarkdown {
        legacyLinks += CommonMark.Node(markdown: source).elements.deep { (inline: Inline) -> [String] in
            guard case let .link(_, _, value) = inline, let url = value else { return [] }
            return [url]
        }
    }
    legacyLinks += content.episodes.flatMap { $0.resources.map(\.url) }
    for link in Set(legacyLinks) {
        guard let url = URLComponents(string: link), url.host == nil || url.host == "talk.objc.io" || url.host == config.baseURL.host,
              let name = url.path.split(separator: "/").last,
              url.path.range(of: #"^/episodes/S01E[0-9]+(-[\p{L}\p{N}-]+)?/?$"#, options: .regularExpression) != nil else { continue }
        let digits = name.dropFirst(4).prefix(while: { $0.isNumber })
        guard let number = Int(digits), let episode = content.episodes.first(where: { $0.number == number }), name != episode.slug else { continue }
        try write(renderer.redirect(to: episode.path), "episodes/\(name)/index.html")
    }
    // Export only the new site's public schema. Never copy whole repositories or server state.
    let encoder = JSONEncoder()
    encoder.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
    encoder.keyEncodingStrategy = .convertToSnakeCase
    let publicEpisodes = content.episodes.map { episode in
        PublicEpisode(number: episode.number, title: content.fullTitle(episode), synopsis: episode.synopsis,
                      url: renderer.absolute(episode.path), releaseAt: ISO8601DateFormatter().string(from: episode.releaseAt),
                      duration: episode.mediaDuration, embedUrl: episode.embedURL, pictureUrl: episode.posterURL,
                      collections: episode.collections, transcriptUrl: renderer.absolute("/transcripts/episode\(episode.number).md"))
    }
    try write(String(decoding: encoder.encode(publicEpisodes), as: UTF8.self), "episodes.json")
    try write(String(decoding: encoder.encode(content.collections), as: UTF8.self), "collections.json")
    try write(renderer.rss, "episodes.rss")
    try write(renderer.sitemap, "sitemap.xml")
    try write(renderer.redirect(to: "/sitemap.xml"), "sitemap/index.html")
    try write("User-agent: *\nAllow: /\nSitemap: \(renderer.absolute("/sitemap.xml"))\n", "robots.txt")
    try write(renderer.notFound, "404.html")
    try copy(config.assets.appendingPathComponent("fonts"), "assets/fonts")
    try copy(config.assets.appendingPathComponent("images/collections"), "assets/images/collections")
    try copy(config.assets.appendingPathComponent("images/logo.svg"), "assets/images/logo.svg")
    try copy(config.assets.appendingPathComponent("stylesheets/application.css"), "assets/stylesheets/application.css")
    for name in ["pattern-blue-0f88229c.png", "pattern-shade-2cd38563.png", "pattern-white-transparent.png"] {
        try copy(config.assets.appendingPathComponent("images/\(name)"), "assets/images/\(name)")
    }
    try copy(config.assets.appendingPathComponent("favicon.ico"), "favicon.ico")
    for name in ["static-site.css", "static-site.js", "search.js", "search-results.js"] {
        try copy(config.siteAssets.appendingPathComponent(name), "assets/\(name)")
    }
    if let executable = config.pagefind {
        let process = Process()
        process.executableURL = executable
        process.arguments = ["--site", staging.path, "--output-subdir", "pagefind"]
        try process.run()
        process.waitUntilExit()
        guard process.terminationReason == .exit, process.terminationStatus == 0,
              fm.fileExists(atPath: staging.appendingPathComponent("pagefind/pagefind.js").path) else {
            throw BuildError("Pagefind indexing failed. The previous site has been preserved.")
        }
    }
    // Complete and validate the build before touching the previous output.
    if fm.fileExists(atPath: output.path) {
        let backup = parent.appendingPathComponent(".swift-talk-backup-\(UUID().uuidString)")
        try fm.moveItem(at: output, to: backup)
        do {
            try fm.moveItem(at: staging, to: output)
        } catch {
            try fm.moveItem(at: backup, to: output)
            throw error
        }
        try fm.removeItem(at: backup)
    } else {
        try fm.moveItem(at: staging, to: output)
    }
    return BuildSummary(episodes: content.episodes.count, collections: content.collections.count, output: output)
}

private struct PublicEpisode: Encodable {
    var number: Int
    var title: String
    var synopsis: String
    var url: String
    var releaseAt: String
    var duration: Double
    var embedUrl: String
    var pictureUrl: String?
    var collections: [String]
    var transcriptUrl: String
}
